import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import sharp from 'sharp';

const root = new URL('../', import.meta.url),
  destination = new URL('public/brand/optimized/', root);
await mkdir(destination, { recursive: true });
const measurements = [];
async function output(name, bytes, extension) {
  const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 12);
  const filename = `${name}-${hash}.${extension}`;
  await writeFile(new URL(filename, destination), bytes);
  return '/brand/optimized/' + filename;
}
async function encode(name, source, width, quality = 86) {
  const original = await readFile(new URL('public/brand/' + source, root));
  const bytes = await sharp(original)
    .resize({ width, withoutEnlargement: true })
    .webp({ quality, alphaQuality: 100, effort: 6 })
    .toBuffer();
  measurements.push({ name, originalBytes: original.length, optimizedBytes: bytes.length });
  return { src: await output(name, bytes, 'webp'), bytes };
}
const assets = {
  illustration: (await encode('illustration', 'forum-illustration.svg', 768, 88)).src,
  logo: await output('logo', await readFile(new URL('public/brand/forum-logo.svg', root)), 'svg'),
  atlases: {},
  banners: {},
};
for (const [name, columns] of [
  ['community', 4],
  ['editor', 4],
  ['actions', 5],
  ['admin', 5],
])
  assets.atlases[name] = (await encode(name, `ui-red/${name}.png`, columns * 128, 90)).src;
for (const name of ['experience', 'projects', 'skills'])
  assets.banners[name] = {
    src: (await encode(name, `forum-banners/${name}.svg`, 2172, 85)).src,
    small: (await encode(name + '-small', `forum-banners/${name}.svg`, 1086, 85)).src,
  };
const buttons = await encode('buttons', 'ui-red/buttons.png', 864, 92);
// The mini program shares the same neutral identity and lightweight banners.
const miniAssets = new URL('wechat/miniprogram/assets/', root);
await mkdir(miniAssets, { recursive: true });
await writeFile(new URL('logo.png', miniAssets), await sharp(await readFile(new URL('public/brand/forum-logo.svg', root))).png().toBuffer());
for (const [name, filename] of [['experience', 'home-banner.webp'], ['projects', 'projects-banner.webp'], ['skills', 'skills-banner.webp']])
  await writeFile(new URL(filename, miniAssets), await readFile(new URL('public' + assets.banners[name].small, root)));
assets.buttonAtlas = buttons.src;
const views = [
  ['primary', 0, 0],
  ['secondary', 1086, 0],
  ['selected', 0, 362],
  ['pressed', 1086, 362],
];
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1086" height="362" viewBox="0 0 1086 362">${views.map(([id, x, y]) => `<view id="${id}" viewBox="${x} ${y} 1086 362"/>`).join('')}<image width="2172" height="724" href="data:image/webp;base64,${buttons.bytes.toString('base64')}"/></svg>`;
assets.buttonSkins = await output('button-skins', Buffer.from(svg), 'svg');
await writeFile(
  new URL('src/brand-assets.ts', root),
  '// Generated by scripts/optimize-brand-assets.mjs; original artwork is retained.\nexport const brandAssets = ' +
    JSON.stringify(assets, null, 2) +
    ' as const;\n',
);
await writeFile(
  new URL('src/brand-assets.css', root),
  `/* Generated image URLs: filenames change when their contents change. */\n:root {\n  --brand-button-atlas: url('${assets.buttonAtlas}');\n  --brand-forum-art: url('${assets.banners.skills.src}');\n${views.map(([id]) => `  --brand-skin-${id}: url('${assets.buttonSkins}#${id}');`).join('\n')}\n}\n`,
);
await writeFile(
  new URL('public/brand/optimized/sizes.json', root),
  JSON.stringify(measurements, null, 2),
);
